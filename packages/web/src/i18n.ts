export type StringKey = keyof (typeof STRINGS)['en'];

let current: Lang = 'en';

export function resolveLang(setting: LangSetting): Lang {
  if (setting !== 'auto') return setting;
  const nav = typeof navigator !== 'undefined' ? navigator.language : 'en';
  return nav.toLowerCase().startsWith('ko') ? 'ko' : 'en';
}

export function setLang(l: Lang): void {
  current = l;
  document.documentElement.lang = l;
}

export function getLang(): Lang {
  return current;
}

export function t(key: StringKey, params?: Record<string, string | number>): string {
  const table = STRINGS[current] as Record<string, string>;
  let s = table[key] ?? (STRINGS.en as Record<string, string>)[key] ?? key;
  if (params) for (const [k, v] of Object.entries(params)) s = s.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
  return s;
}

export function upgradeName(id: string): string {
  return t(`up.${id}.name` as StringKey);
}
export function upgradeDesc(id: string): string {
  return t(`up.${id}.desc` as StringKey);
}
